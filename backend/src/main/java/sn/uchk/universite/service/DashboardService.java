package sn.uchk.universite.service;

import com.itextpdf.text.Document;
import com.itextpdf.text.Paragraph;
import com.itextpdf.text.pdf.PdfWriter;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Service;
import sn.uchk.universite.dto.DashboardStatsDTO;
import sn.uchk.universite.repository.*;

import java.io.ByteArrayOutputStream;

@Service
@RequiredArgsConstructor
public class DashboardService {

    private final EtudiantRepository etudiantRepository;
    private final FormateurRepository formateurRepository;
    private final FormationRepository formationRepository;
    private final StageRepository stageRepository;
    private final ReunionRepository reunionRepository;
    private final DocumentRepository documentRepository;

    // ============================
    // STATISTIQUES
    // ============================
    public DashboardStatsDTO statistiques() {

        DashboardStatsDTO dto = new DashboardStatsDTO();

        dto.setNombreEtudiants(etudiantRepository.count());
        dto.setNombreFormateurs(formateurRepository.count());
        dto.setNombreFormations(formationRepository.count());
        dto.setNombreStages(stageRepository.count());
        dto.setNombreReunions(reunionRepository.count());
        dto.setNombreDocuments(documentRepository.count());

        return dto;
    }

    // ============================
    // EXPORT PDF
    // ============================
    public ResponseEntity<byte[]> exportPdf() {

        DashboardStatsDTO stats = statistiques();

        ByteArrayOutputStream outputStream = new ByteArrayOutputStream();

        try {

            // IMPORTANT : éviter conflit avec entity Document
            Document pdfDoc = new Document();

            PdfWriter.getInstance(pdfDoc, outputStream);

            pdfDoc.open();

            pdfDoc.add(new Paragraph("==================================="));
            pdfDoc.add(new Paragraph("        RAPPORT ADMINISTRATEUR      "));
            pdfDoc.add(new Paragraph("==================================="));
            pdfDoc.add(new Paragraph(" "));

            pdfDoc.add(new Paragraph("STATISTIQUES GENERALES"));
            pdfDoc.add(new Paragraph(" "));

            pdfDoc.add(new Paragraph("Etudiants      : " + stats.getNombreEtudiants()));
            pdfDoc.add(new Paragraph("Formateurs     : " + stats.getNombreFormateurs()));
            pdfDoc.add(new Paragraph("Formations     : " + stats.getNombreFormations()));
            pdfDoc.add(new Paragraph("Stages         : " + stats.getNombreStages()));
            pdfDoc.add(new Paragraph("Reunions      : " + stats.getNombreReunions()));
            pdfDoc.add(new Paragraph("Documents     : " + stats.getNombreDocuments()));

            pdfDoc.add(new Paragraph(" "));
            pdfDoc.add(new Paragraph("==================================="));
            pdfDoc.add(new Paragraph("Generated by University System"));

            pdfDoc.close();

        } catch (Exception e) {

            throw new RuntimeException(
                    "Erreur lors de la génération du PDF",
                    e
            );

        }

        return ResponseEntity.ok()
                .header(
                        HttpHeaders.CONTENT_DISPOSITION,
                        "attachment; filename=rapport-admin.pdf"
                )
                .contentType(MediaType.APPLICATION_PDF)
                .body(outputStream.toByteArray());
    }
}